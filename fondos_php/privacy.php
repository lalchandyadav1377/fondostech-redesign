                        <p>We may disclose Customer Data in the following circumstances:</p>
                        <ul class="legal-list">
                            <li><strong>(a) Subsidiaries, affiliates, and service providers.</strong> We may share Customer Data with our subsidiaries, affiliates, and third-party service providers (including hosting providers, CRM platforms, analytics providers, email outreach and verification tools, and scheduling tools), whether located within or outside India, solely to the extent necessary for them to perform their specific services. We make commercially reasonable efforts to ensure such parties keep Customer Data confidential as per industry standards, and all such vendors are subject to contractual data protection obligations and periodic review.</li>
