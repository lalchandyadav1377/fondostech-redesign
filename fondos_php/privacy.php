                            <li><strong>(d)</strong> Content stored in connection with your use of the platform, including quote data, policy details, claims information, and employee/POSP records entered by you or your team.</li>
                            <li><strong>(e)</strong> Information automatically received and recorded via server logs and cookies, including your IP address, browser type, operating system, and the pages you visit, collected via Google Analytics (GA4) and Google Tag Manager (GTM).</li>
                            <li><strong>(f)</strong> Information from advertising and marketing platforms (Google Ads, LinkedIn Ads and its Conversions API, HubSpot/Zoho CRM, Calendly) when you interact with our campaigns or communications.</li>
                        </ul>
