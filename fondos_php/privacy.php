                    <section class="legal-block" id="background">
                        <h2>Background</h2>
                        <p>
                            Fondos Technologies Private Limited (“FondosTech,” “Company,” “we,” “us,” or “our”) adheres to applicable Indian data protection law, including the Digital Personal Data Protection Act, 2023 (“DPDP Act”), the Information Technology Act, 2000, and the Information Technology (Reasonable Security Practices and Procedures and Sensitive Personal Data or Information) Rules, 2011.
                        </p>
                        <p>
                            This Privacy Policy explains how FondosTech collects, receives, stores, processes, discloses, transfers, and otherwise handles data in connection with the website fondostech.in and the FondosTech platform, including FT Insure, FT Digital Claims, FT EB Sure, FT Recon, FT Payin &amp; Out, and FT Compliance (together, the “Website/App”).
                        </p>
                    </section>

                    <section class="legal-block" id="definitions">
                        <h2>Definitions</h2>
                        <ul class="legal-list">
                            <li><strong>“Personal Data”</strong> means any data about an individual who is identifiable by or in relation to such data.</li>
                            <li><strong>“Sensitive Personal Data”</strong> includes financial information and any other categories of sensitive data as defined under applicable law.</li>
                            <li><strong>“Data Principal”</strong> means the individual to whom the Personal Data relates.</li>
                            <li><strong>“Data Fiduciary”</strong> means the entity that determines the purpose and means of processing Personal Data.</li>
                            <li><strong>“Data Processor”</strong> means FondosTech, or any third party processing data on FondosTech’s behalf.</li>
                            <li><strong>“Customer Data”</strong> means all information described in Section 1 below.</li>
                        </ul>
                        <div class="legal-callout">
                            <div class="legal-callout-label">Data Fiduciary and Data Processor</div>
                            <p>
                                Where a broker, POSP network, bank, or other business customer uses the FondosTech platform to process their own end-customers’/policyholders’ data, that customer is the Data Fiduciary for that data, and FondosTech acts as a Data Processor, strictly on that customer’s instructions and under the terms of the applicable Order Form/Data Processing Agreement (“DPA”). This Policy primarily addresses FondosTech’s own processing, as a Data Fiduciary, of data belonging to website visitors, prospects, and platform account users.
                            </p>
                        </div>
                    </section>

